"""
BPAI QA Automation - Portal persona exporter
---------------------------------------------
Turns an avatar's persona file into a paste-ready sheet for the QA Lab's
Personas tab, so the portal and the code never drift apart.

    python core/export_portal_personas.py Gladys
    python core/export_portal_personas.py Gladys --out avatars/gladys/settings/PORTAL_PERSONAS.md

Each persona becomes one block with every QA Lab field filled in:

    QA Lab field                      comes from
    --------------------------------  ----------------------------------------
    User context (top of the tab)     SHARED_CONTEXT
    Name                              the LIBRARY key
    Kind                              EXPECTATIONS[...]["portal_kind"]
    How this user behaves             the LIBRARY value
    What it should score lowest/high  EXPECTATIONS[...]["portal_band"]
    The avatar should                 EXPECTATIONS[...]["avatar_pass"]
    The avatar must not               EXPECTATIONS[...]["avatar_fail"]
    The coaching should               EXPECTATIONS[...]["coaching_expect"]
    Follow-up answers should          EXPECTATIONS[...]["mentoring_expect"]
    Notes                             EXPECTATIONS[...]["tests"] + per_point

An avatar whose persona file has no EXPECTATIONS entry for a persona still gets
a block, with the judge fields left blank and a note saying so.
"""

# --- repo bootstrap -------------------------------------------------------
# Puts the repo root on the import path, so this runs as
# `python core/export_portal_personas.py` from the repo root. config/settings.py and personas/ live
# there; the rest of the engine sits next to this file.
import pathlib as _pathlib, sys as _sys
_sys.path.insert(0, str(_pathlib.Path(__file__).resolve().parents[1]))
# --------------------------------------------------------------------------

import argparse
import sys


def load_avatar_module(avatar):
    """Finds avatars/<avatar>/personas.py, matching the folder name case-insensitively."""
    import personas

    folder, module = personas.load(avatar)
    if module is None:
        raise SystemExit(f"No persona file for {avatar!r}. "
                         f"Available: {', '.join(sorted(personas.MODULES))}")
    module._source_path = personas.path_for(folder)
    return module


def lines_block(items, empty="(none listed)"):
    if not items:
        return empty
    return "\n".join(str(i) for i in items)


def render(module, avatar_label):
    library = module.LIBRARY
    expectations = getattr(module, "EXPECTATIONS", {}) or {}
    active = set(module.PERSONAS[avatar_label]["personas"]) if avatar_label in module.PERSONAS else set()
    total = _rubric_total(module)

    out = []
    out.append(f"# {avatar_label} - QA Lab persona sheet\n")
    out.append("Generated by `core/export_portal_personas.py` from "
               f"`{getattr(module, '_source_path', 'the avatar persona file')}`. Regenerate rather than editing by hand.\n")
    out.append("---\n")
    out.append("## Before you start: set the scoring table first\n")
    out.append(f"Every band below is **out of {total}**. The QA Lab takes that denominator from the "
               "situation's scoring table, so enter the scoring-table rows BEFORE typing any persona "
               "band. If the table is still on its default, the Personas tab will show "
               "\"out of 10\" and every band you type will be recorded against the wrong scale.\n")
    out.append("---\n")
    out.append("## User context\n")
    out.append("Paste into the **User context** box at the top of the Personas tab, then Save context.\n")
    out.append("The portal refuses rubric or best-practice wording here. This text is already written to "
               "that rule: it is the objective and the avatar's background only.\n")
    out.append("```\n" + module.SHARED_CONTEXT + "\n```\n")
    out.append("---\n")

    standard = [n for n in library if expectations.get(n, {}).get("portal_kind") != "Probe"]
    probes = [n for n in library if expectations.get(n, {}).get("portal_kind") == "Probe"]
    out.append(f"## Personas to create ({len(library)})\n")
    out.append(f"**Standard ({len(standard)}):** {', '.join(standard)}\n")
    out.append(f"**Probes ({len(probes)}):** {', '.join(probes)}\n")
    out.append("Personas currently in this file's RUN_SET (what the Python runner would use right now): "
               f"{', '.join(sorted(active)) if active else '(none)'}\n")
    out.append("---\n")

    for index, name in enumerate(library, start=1):
        exp = expectations.get(name, {})
        band = exp.get("portal_band")
        kind = exp.get("portal_kind", "Standard")
        out.append(f"## {index}. {name}\n")
        if not exp:
            out.append("> No EXPECTATIONS entry for this persona - the judge fields below are blank.\n")

        out.append("**Name**\n")
        out.append(f"```\n{name}\n```\n")
        out.append(f"**Kind:** `{kind}`  **Active:** on\n")
        out.append("**How this user behaves**\n")
        out.append("```\n" + library[name].strip() + "\n```\n")

        if band:
            out.append(f"**What it should score:** lowest `{band[0]}`, highest `{band[1]}` (out of {total})\n")
        else:
            out.append("**What it should score:** (no band recorded)\n")

        out.append("**The avatar should** (one per line)\n")
        out.append("```\n" + lines_block(exp.get("avatar_pass")) + "\n```\n")
        out.append("**The avatar must not** (one per line)\n")
        out.append("```\n" + lines_block(exp.get("avatar_fail")) + "\n```\n")
        out.append("**The coaching should**\n")
        out.append("```\n" + (exp.get("coaching_expect") or "(none listed)") + "\n```\n")
        out.append("**Follow-up answers should**\n")
        out.append("```\n" + (exp.get("mentoring_expect") or "(none listed)") + "\n```\n")

        notes = []
        if exp.get("tests"):
            notes.append(f"Tests: {exp['tests']}")
        if exp.get("per_point"):
            notes.append("Expected per category: "
                         + ", ".join(f"{k} {v}" for k, v in exp["per_point"].items()))
        if exp.get("score_band"):
            notes.append(f"Band reasoning: {exp['score_band']}")
        out.append("**Notes**\n")
        out.append("```\n" + ("\n".join(notes) if notes else "(none)") + "\n```\n")
        out.append("---\n")

    return "\n".join(out)


def _rubric_total(module):
    """Sums the per_point categories of the first persona that lists plain numbers."""
    for exp in (getattr(module, "EXPECTATIONS", {}) or {}).values():
        per_point = exp.get("per_point") or {}
        if per_point and all(isinstance(v, int) for v in per_point.values()):
            return sum(per_point.values())
    return 100


def main():
    parser = argparse.ArgumentParser(description=__doc__,
                                     formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("avatar", help="avatar name, e.g. Gladys")
    parser.add_argument("--out", help="write here instead of printing to the screen")
    args = parser.parse_args()

    module = load_avatar_module(args.avatar)
    label = next(iter(module.PERSONAS))
    text = render(module, label)

    if args.out:
        with open(args.out, "w", encoding="utf-8") as handle:
            handle.write(text)
        print(f"Wrote {args.out} ({text.count(chr(10))} lines, {len(module.LIBRARY)} personas).")
    else:
        print(text)
    return 0


if __name__ == "__main__":
    sys.exit(main())
